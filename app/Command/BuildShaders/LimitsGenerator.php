<?php

declare(strict_types=1);

namespace Serafim\Doom\Command\BuildShaders;

use Serafim\Doom\Exception\DataFileException;

/**
 * Turns the numbers that the shaders and the renderer share (`limits.json`) into the constants of `limits.glsl`.
 */
final readonly class LimitsGenerator
{
    public const string SOURCE = 'limits.json';

    public const string TARGET = 'limits.glsl';

    /**
     * Writes `limits.glsl` next to `limits.json`.
     *
     * @param non-empty-string $directory
     *
     * @return non-empty-string|null pathname of the written file, {@see null} for a directory without `limits.json`
     * @throws DataFileException in case of the file is not valid
     */
    public function generate(string $directory): ?string
    {
        $source = $directory . '/' . self::SOURCE;

        if (!\is_file($source)) {
            return null;
        }

        $target = $directory . '/' . self::TARGET;

        \file_put_contents($target, $this->render($source));

        return $target;
    }

    /**
     * @param non-empty-string $source pathname of `limits.json`
     *
     * @throws DataFileException in case of the file is not valid
     */
    public function render(string $source): string
    {
        $json = @\file_get_contents($source);

        if ($json === false) {
            throw DataFileException::becauseFileIsNotReadable($source);
        }

        try {
            $limits = \json_decode($json, true, 512, \JSON_THROW_ON_ERROR);
        } catch (\JsonException $e) {
            throw DataFileException::becauseJsonIsInvalid($source, $e->getMessage(), $e);
        }

        if (!\is_array($limits)) {
            throw DataFileException::becauseJsonIsInvalid($source, 'the root is not an object');
        }

        $lines = ['// Generated by `php bin/doom build-shaders` from limits.json, do not edit.'];

        foreach ($limits as $name => $value) {
            $lines[] = $this->renderConstant($source, (string) $name, $value);
        }

        return \implode("\n", $lines) . "\n";
    }

    /**
     * @throws DataFileException in case of the value is neither an integer nor a number
     */
    private function renderConstant(string $source, string $name, mixed $value): string
    {
        $constant = \strtoupper((string) \preg_replace('/(?<!^)[A-Z]/', '_$0', $name));

        if (\is_int($value)) {
            return \sprintf('const int %s = %d;', $constant, $value);
        }

        if (\is_float($value)) {
            return \sprintf('const float %s = %s;', $constant, \var_export($value, true));
        }

        throw DataFileException::becauseFieldIsInvalid($source, $name, 'an integer or a number');
    }
}
